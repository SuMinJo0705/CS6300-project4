class WorstCaseBustersAgent(ExpectedDistanceBustersAgent):
    "An agent that charges the ghost it is surest of reaching, planning for the worst case."
    
    # Provided (not graded): see "Analysis questions: Worst Case vs. Expected
    # Utility Agents" in the project spec.

    def chooseAction(self, gameState: busters.GameState):
        """
        Scores each legal action by how close it brings Pacman to a ghost in
        the worst case, and returns the action with the best (lowest) score.

        For a legal action, let succ be Pacman's position after taking it.
        For each living ghost, the worst-case distance from succ to that ghost
        is the largest maze distance (self.distancer.getDistance) from succ to
        any position where that ghost's belief is nonzero. The action's score
        is the minimum of the worst-case distances over all living ghosts.

        Return the action with the minimum score. Break ties by taking the
        action that comes first in `legal`.

        This agent is provided; you do not need to modify it.
        """
        pacmanPosition = gameState.getPacmanPosition()
        legal = [a for a in gameState.getLegalPacmanActions()]
        livingGhosts = gameState.getLivingGhosts()
        livingGhostPositionDistributions = \
            [beliefs for i, beliefs in enumerate(self.ghostBeliefs)
             if livingGhosts[i+1]]
        bestAction, bestScore = None, None
        for action in legal:
            successorPosition = Actions.getSuccessor(pacmanPosition, action)
            score = min(max(self.distancer.getDistance(successorPosition, pos)
                            for pos, prob in beliefs.items() if prob > 0)
                        for beliefs in livingGhostPositionDistributions)
            if bestScore is None or score < bestScore:
                bestAction, bestScore = action, score
        return bestAction
